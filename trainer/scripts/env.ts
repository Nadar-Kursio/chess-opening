/**
 * Writes the per-environment settings:
 *   npm run env:prod -> .env.production.local  (shared Kursio RDS, from Secrets Manager chesslab/*)
 *   npm run env:dev  -> .env.development.local (local Docker database)
 * Next loads the matching file for `next start` / `next dev`; scripts load it with --env-file.
 */
import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

type Stage = 'prod' | 'dev';

const STAGES = {
  prod: { file: '.env.production.local', port: 3020, url: 'https://new.chesslab.dev' },
  dev: { file: '.env.development.local', port: 3021, url: 'http://localhost:3021' },
} satisfies Record<Stage, { file: string; port: number; url: string }>;

function secret(id: string) {
  const raw = execFileSync('aws', [
    'secretsmanager',
    'get-secret-value',
    '--secret-id',
    id,
    '--query',
    'SecretString',
    '--output',
    'text',
  ]);
  return JSON.parse(raw.toString()) as Record<string, string>;
}

/** Keeps a dev auth secret across runs so regenerating the file doesn't sign everyone out. */
function existingValue(file: string, key: string) {
  if (!existsSync(file)) return null;
  return readFileSync(file, 'utf8').match(new RegExp(`^${key}=(.+)$`, 'm'))?.[1] ?? null;
}

const stage = process.argv[2] as Stage;
if (stage !== 'prod' && stage !== 'dev') throw new Error('Usage: env.ts prod|dev');
const { file, port, url } = STAGES[stage];

const values: Record<string, string> =
  stage === 'prod'
    ? {
        DATABASE_URL: secret('chesslab/db-credentials').url,
        // The RDS instance is shared with Kursio; keep this process's share small.
        DB_POOL_MAX: '5',
        ...(({ BETTER_AUTH_SECRET, EDGE_SECRET }) => ({ BETTER_AUTH_SECRET, EDGE_SECRET }))(
          secret('chesslab/app-secrets'),
        ),
      }
    : {
        DATABASE_URL: 'postgres://chesslab:chesslab@localhost:5520/chesslab',
        BETTER_AUTH_SECRET:
          existingValue(file, 'BETTER_AUTH_SECRET') ?? randomBytes(32).toString('base64'),
      };

const lines = [
  `# Generated by \`npm run env:${stage}\`. Regenerate rather than edit.`,
  ...Object.entries({
    ...values,
    BETTER_AUTH_URL: url,
    BETTER_AUTH_TRUSTED_ORIGINS: `${url},http://localhost:${port}`,
    CONTENT_DIR: path.join(process.cwd(), 'content'),
  }).map(([key, value]) => `${key}=${value}`),
];
writeFileSync(file, `${lines.join('\n')}\n`, { mode: 0o600 });
console.log(`Wrote ${file} (${url}).`);
